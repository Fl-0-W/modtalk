    public static Profile profile(String type, boolean hostile) {
        Profile p = MAP.get(type);
        if (p != null) return p;
        return new Profile(
                "Характер: ты существо типа «" + type + "» из мира Minecraft. Придумай себе яркий характер, "
                        + (hostile ? "ты агрессивен, но с тобой можно договориться." : "ты дружелюбен и любопытен."),
                "alloy", 1.0, hostile ? RULES_TRUCE : "");
    }

    public static String systemPrompt(String type, boolean hostile, String player, String mobName) {
        Profile p = profile(type, hostile);
        return String.format(COMMON, player, mobName) + p.prompt() + " " + p.rules();
    }
