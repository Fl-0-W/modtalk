    public static Profile profile(String type, boolean hostileFallback) {
        Profile p = MAP.get(type);
        if (p != null) return p;
        return new Profile("Характер вида: ты существо типа «" + type + "» из мира Minecraft. Придумай себе яркий характер"
                + (hostileFallback ? "; ты агрессивен, но с тобой можно договориться." : "; ты дружелюбен и любопытен."),
                1.0, hostileFallback, false);
    }

    public static boolean isHostile(String type, boolean fallback) {
        Profile p = MAP.get(type);
        return p != null ? p.hostile() : fallback;
    }

    /**
     * Подпись моба без выдуманных имён: своё имя (name tag), если игрок его дал; у жителей — профессия
     * («Фермер»); у остальных — название вида («Зомби»). У детёнышей добавляется пометка.
     */
    public static String displayName(Entity e) {
        net.minecraft.text.Text custom = MobTalkClient.realCustomName(e); // без временной метки с номером
        if (custom != null) return custom.getString();
        String base = e.getType().getName().getString();
        if (e instanceof VillagerEntity v) {
            String prof = Registries.VILLAGER_PROFESSION.getId(v.getVillagerData().getProfession()).getPath();
            String label = PROF_LABELS.get(prof);
            if (label != null) base = label;
        }
        if (e instanceof MobEntity m && m.isBaby()) return base + " (малыш)";
        return base;
    }

    /** Название вида по id без пространства имён («zombie» -> «Зомби»). */
    public static String speciesName(String type) {
        Identifier id = Identifier.tryParse("minecraft:" + type);
        if (id != null) {
            Optional<EntityType<?>> t = Registries.ENTITY_TYPE.getOrEmpty(id);
            if (t.isPresent()) return t.get().getName().getString();
        }
        return type;
    }

    /** Индивидуальная личность конкретного моба: черта, тайна, профессия, состояние. */
    public static String persona(MobEntity e) {
        long h = e.getUuid().getMostSignificantBits() ^ e.getUuid().getLeastSignificantBits();
        String quirk = QUIRKS[(int) Math.floorMod(h, (long) QUIRKS.length)];
        String secret = SECRETS[(int) Math.floorMod(h >>> 9, (long) SECRETS.length)];
        StringBuilder sb = new StringBuilder();
        sb.append("Твоя индивидуальная черта: ты ").append(quirk).append(". ");
        sb.append("Твоя тайна или мечта: ты ").append(secret)
                .append(" (раскрывай её, только если отношение игрока к тебе выше +40, и то намёками). ");
        if (e.isBaby()) sb.append("Ты ещё детёныш: говоришь по-детски, наивно и любопытно. ");
        if (e.getHealth() < e.getMaxHealth() * 0.5f) sb.append("Ты ранен и жалуешься на это. ");
        if (e instanceof VillagerEntity v) {
            String prof = Registries.VILLAGER_PROFESSION.getId(v.getVillagerData().getProfession()).getPath();
            String f = PROFESSIONS.get(prof);
            if (f != null) sb.append(f).append(" ");
        }
        return sb.toString();
    }

    public static String systemPrompt(Brain.Mob m, String player, List<String> neighbors,
                                      String inventory, String context, boolean actions) {
        Profile p = profile(m.type(), m.hostile());
        int pers = State.personal(m.id());
        int att = Reputation.attitude(m.id(), m.type());
        int spec = Reputation.factionRep(m.type());
        StringBuilder sb = new StringBuilder();
        sb.append(String.format(COMMON, m.name(), m.type(), player));
        sb.append(p.prompt()).append(" ");
        if (m.persona() != null && !m.persona().isEmpty()) sb.append("\n").append(m.persona());
        sb.append("\nОтношение: итоговое отношение к игроку ").append(Reputation.fmt(att)).append(" из 100 (")
                .append(Reputation.tier(att)).append("); личный опыт общения ").append(Reputation.fmt(pers))
                .append(", слава игрока среди твоих сородичей (")
                .append(Reputation.factionName(Reputation.factionOf(m.type()))).append(") ")
                .append(Reputation.fmt(spec)).append(" (").append(Reputation.tier(spec)).append("). ")
                .append(Reputation.guidance(att, p.trader())).append(" ");
        String sum = Memory.summary(m.id());
        if (!sum.isBlank()) sb.append("\nТвоя память о прошлых разговорах (кратко): ").append(sum).append(" ");
        if (actions) {
            sb.append("\n").append(ACTIONS_BASE);
            if (m.hostile()) sb.append(ACTIONS_TRUCE);
            if (p.trader()) sb.append(ACTIONS_TRADE);
            sb.append(ACTIONS_QUEST);
            String qd = Quests.describeFor(m.id());
            if (!qd.isEmpty()) sb.append("\n").append(qd).append(" ");
        } else {
            sb.append("\nВ этом разговоре поле actions всегда пустое [].");
        }
        if (context != null && !context.isEmpty()) sb.append("\nСейчас в игре: ").append(context).append(". ");
        if (neighbors != null && !neighbors.isEmpty())
            sb.append("\nРядом с тобой также: ").append(String.join(", ", neighbors)).append(". ");
        if (actions && p.trader() && inventory != null)
            sb.append("\nВещи игрока: ").append(inventory).append(". ");
        return sb.toString();
    }
